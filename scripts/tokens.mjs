#!/usr/bin/env node
// Generates the theme's design values from design-tokens.json (Strix design-token standard v1, W3C DTCG).
//
//   npm run tokens            write src/assets/tailwind/tokens.css, src/assets/tailwind/base/typography.js
//                             and the color_schemes in config/settings_data.json
//   npm run tokens -- --check fail when any of those files is out of date (used in CI)
//
// Standard: https://github.com/webweit-gmbh/strix-shopify-design/blob/main/docs/design-token-standard.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(root, 'design-tokens.json');
const OUT = {
    css: path.join(root, 'src/assets/tailwind/tokens.css'),
    typography: path.join(root, 'src/assets/tailwind/base/typography.js'),
    settings: path.join(root, 'config/settings_data.json'),
};
const SCHEME_KEYS = ['background', 'background_gradient', 'text', 'primary_background', 'primary_foreground', 'secondary_background', 'secondary_foreground', 'arrows_color', 'svg_background', 'shadow', 'disabled_background', 'disabled_foreground', 'info_color', 'success_color', 'warning_color', 'error_color'];
const TYPE_CLASSES = ['heading-2xl', 'heading-xl', 'heading-lg', 'heading-base', 'heading-md', 'heading-sm', 'heading-xs', 'heading-2xs', 'heading-3xs', 'description-body', 'description-micro', 'body', 'button', 'link', 'price-list-regular'];
const BREAKPOINTS = ['sm', 'md', 'lg', 'xl', '2xl', '3xl', '4xl', '5xl'];
// Tailwind's own sm/md/lg are rem values; keeping rem when they match leaves the compiled CSS unchanged.
const TAILWIND_REM_BREAKPOINTS = { sm: 640, md: 768, lg: 1024 };
const TEXT_SIZES = { 12: 'xs', 14: 'sm', 16: 'base', 18: 'lg', 20: 'xl', 24: '2xl', 30: '3xl', 36: '4xl', 48: '5xl', 60: '6xl', 72: '7xl', 96: '8xl', 128: '9xl' };
const LEADING = { 1.3: 'tight', 1.5: 'normal', 1: 'none' };
const TRACKING = { '0.01em': '1', '0.02em': '2' };
const HEADER = 'Generated by `npm run tokens` from design-tokens.json. Do not edit by hand.';

const fail = (message) => {
    console.error('tokens: ' + message);
    process.exit(1);
};
const isToken = (v) => v && typeof v === 'object' && !Array.isArray(v) && '$value' in v;
const lookup = (doc, ref) => ref.split('.').reduce((node, key) => (node && typeof node === 'object' ? node[key] : undefined), doc);
function resolve(doc, value, seen = []) {
    const m = typeof value === 'string' && value.match(/^\{([^{}]+)\}$/);
    if (!m) return value;
    if (seen.includes(m[1])) fail('reference cycle: ' + [...seen, m[1]].join(' → '));
    const target = lookup(doc, m[1]);
    if (!isToken(target)) fail('unknown reference {' + m[1] + '}');
    return resolve(doc, target.$value, [...seen, m[1]]);
}
const value = (doc, p) => {
    const t = lookup(doc, p);
    return isToken(t) ? resolve(doc, t.$value) : undefined;
};
const entries = (group) => Object.entries(group || {}).filter(([k]) => !k.startsWith('$'));
const px = (v) => {
    const m = String(v).match(/^(-?[\d.]+)px$/);
    if (!m) fail('expected a px dimension, got "' + v + '"');
    return Number(m[1]);
};
const rem = (n) => +(n / 16).toFixed(4) + 'rem';
const hex = (v, where) => {
    if (!/^#(?:[0-9a-f]{6}|[0-9a-f]{8})$/i.test(String(v))) fail(where + ': "' + v + '" is not a hex colour');
    return String(v).toLowerCase();
};
const fontStack = (list) => (Array.isArray(list) ? list : [list]).map((f) => (/^[\w-]+$/.test(f) && !/\s/.test(f) && !/^[A-Z]/.test(f) ? f : `'${f}'`)).join(', ');

function readTokens() {
    if (!fs.existsSync(SOURCE)) fail('design-tokens.json not found at the theme root');
    let doc;
    try {
        doc = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
    } catch (e) {
        fail('design-tokens.json is not valid JSON: ' + e.message);
    }
    if (doc.$extensions?.['nl.strix']?.schemaVersion !== 1) fail('design-tokens.json must have $extensions["nl.strix"].schemaVersion 1');
    for (const p of ['font.family.body', 'typography.body']) if (!isToken(lookup(doc, p))) fail('missing ' + p);
    for (const k of BREAKPOINTS) if (!isToken(lookup(doc, 'breakpoint.' + k))) fail('missing breakpoint.' + k);
    const schemes = entries(lookup(doc, 'color.scheme'));
    if (!schemes.length) fail('add at least one color.scheme');
    for (const [id, scheme] of schemes) for (const k of SCHEME_KEYS) if (!isToken(scheme[k])) fail(`color.scheme.${id} is missing ${k}`);
    return doc;
}

function css(doc) {
    const lines = [];
    const palette = lookup(doc, 'color.palette') || {};
    for (const [name, node] of entries(palette)) {
        if (isToken(node)) lines.push(`    --color-${name}: ${hex(resolve(doc, node.$value), 'color.palette.' + name)};`);
        else for (const [step, token] of entries(node)) lines.push(`    --color-${name}-${step}: ${hex(resolve(doc, token.$value), `color.palette.${name}.${step}`)};`);
    }
    for (const role of ['heading', 'body', 'accent']) {
        const family = value(doc, 'font.family.' + role);
        if (family) lines.push(`    --font-${role}: ${fontStack(family)};`);
    }
    for (const k of BREAKPOINTS) {
        const n = px(value(doc, 'breakpoint.' + k));
        lines.push(`    --breakpoint-${k}: ${TAILWIND_REM_BREAKPOINTS[k] === n ? rem(n) : n + 'px'};`);
    }
    for (const [name, token] of entries(lookup(doc, 'radius'))) lines.push(`    --radius-${name}: ${rem(px(resolve(doc, token.$value)))};`);
    for (const [name, token] of entries(lookup(doc, 'motion.ease'))) {
        const v = resolve(doc, token.$value);
        lines.push(`    --ease-${name}: ${Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : v};`);
    }
    const padding = [];
    for (const size of ['xs', 's', 'm', 'l'])
        for (const device of ['desktop', 'mobile']) {
            const v = value(doc, `spacing.section.${device}.${size}`);
            if (v !== undefined) padding.push(`        --${device}-padding-${size}: ${rem(px(v))};`);
        }
    const ring = ['color', 'width', 'offset'].map((k) => value(doc, 'focus.ring.' + k));
    // Exposed as variables only: a global :focus-visible rule would change how existing themes look.
    if (ring.every((v) => v !== undefined)) padding.push(`        --focus-ring-color: ${hex(ring[0], 'focus.ring.color')};`, `        --focus-ring-width: ${ring[1]};`, `        --focus-ring-offset: ${ring[2]};`);
    return `/* ${HEADER} */\n\n@theme {\n${lines.join('\n')}\n}\n\n@layer base {\n    body {\n${padding.join('\n')}\n    }\n}\n`;
}

function typography(doc) {
    const rules = [];
    const sizeClass = (n, prefix = '') => prefix + (TEXT_SIZES[n] ? 'text-' + TEXT_SIZES[n] : `text-[${rem(n)}]`);
    const headingFamily = JSON.stringify(value(doc, 'font.family.heading') ?? null);
    const bodyFamily = JSON.stringify(value(doc, 'font.family.body'));
    for (const cls of TYPE_CLASSES) {
        const token = lookup(doc, 'typography.' + cls);
        if (!isToken(token)) continue;
        const v = token.$value;
        const mobile = px(resolve(doc, v.fontSize));
        const desktopValue = token.$extensions?.['nl.strix']?.desktop?.fontSize;
        const desktop = desktopValue === undefined ? undefined : px(desktopValue);
        const parts = [sizeClass(mobile)];
        const line = Number(v.lineHeight);
        if (v.lineHeight !== undefined) parts.push(LEADING[line] ? 'leading-' + LEADING[line] : `leading-[${line}]`);
        const tracking = String(v.letterSpacing ?? '0');
        if (tracking !== '0' && tracking !== '0em') parts.push(TRACKING[tracking] ? 'tracking-' + TRACKING[tracking] : `tracking-[${tracking}]`);
        if (desktop !== undefined) parts.push(sizeClass(desktop, 'md:'));
        // Headings only set their font when it differs from the body font, so a single-font theme compiles as before.
        const family = JSON.stringify(resolve(doc, v.fontFamily));
        if (family !== bodyFamily && family === headingFamily) parts.unshift('font-heading');
        else if (family !== bodyFamily) parts.unshift(`font-[${fontStack(JSON.parse(family)).replace(/ /g, '_')}]`);
        rules.push(`        '.${cls}': {\n            '@apply ${parts.join(' ')}': {},\n        },`);
    }
    return `// ${HEADER}\n// Type classes from design-tokens.json → typography. Sizes switch at md, as in Kickstarter.\nmodule.exports = function ({ addComponents }) {\n    addComponents({\n${rules.join('\n\n')}\n    });\n};\n`;
}

function settings(doc, current) {
    const start = current.indexOf('*/');
    const header = start >= 0 ? current.slice(0, start + 2) + '\n' : '';
    const data = JSON.parse(start >= 0 ? current.slice(start + 2) : current);
    data.current ??= {};
    data.current.color_schemes = Object.fromEntries(
        entries(lookup(doc, 'color.scheme')).map(([id, scheme]) => [
            id,
            {
                settings: Object.fromEntries(
                    SCHEME_KEYS.map((k) => {
                        const v = resolve(doc, scheme[k].$value);
                        return [k, k === 'background_gradient' ? (v === 'none' ? '' : String(v)) : hex(v, `color.scheme.${id}.${k}`)];
                    }),
                ),
            },
        ]),
    );
    return header + JSON.stringify(data, null, 2) + '\n';
}

// Templates and section groups store scheme ids (e.g. "color-scheme-1"); renaming schemes would leave them dangling.
function danglingSchemes(doc) {
    const ids = new Set(entries(lookup(doc, 'color.scheme')).map(([id]) => id));
    const found = [];
    for (const dir of ['templates', 'sections']) {
        const walk = (d) => {
            if (!fs.existsSync(d)) return;
            for (const f of fs.readdirSync(d, { withFileTypes: true })) {
                const full = path.join(d, f.name);
                if (f.isDirectory()) walk(full);
                else if (f.name.endsWith('.json'))
                    for (const m of fs.readFileSync(full, 'utf8').matchAll(/"color_scheme[\w-]*"\s*:\s*"([^"]+)"/g))
                        if (!ids.has(m[1])) found.push(`${path.relative(root, full)} → ${m[1]}`);
            }
        };
        walk(path.join(root, dir));
    }
    return [...new Set(found)];
}

const doc = readTokens();
const dangling = danglingSchemes(doc);
if (dangling.length) console.warn('tokens: warning — these templates use colour schemes that design-tokens.json no longer defines:\n  ' + dangling.slice(0, 20).join('\n  ') + (dangling.length > 20 ? `\n  … ${dangling.length - 20} more` : ''));
const settingsNow = fs.readFileSync(OUT.settings, 'utf8');
const outputs = [
    [OUT.css, css(doc)],
    [OUT.typography, typography(doc)],
    [OUT.settings, settings(doc, settingsNow)],
];
const same = (file, text) => fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === text;
if (process.argv.includes('--check')) {
    const stale = outputs.filter(([file, text]) => !same(file, text)).map(([file]) => path.relative(root, file));
    if (stale.length) fail('out of date, run `npm run tokens`: ' + stale.join(', '));
    console.log('tokens: up to date');
} else {
    for (const [file, text] of outputs)
        if (!same(file, text)) {
            fs.writeFileSync(file, text);
            console.log('tokens: wrote ' + path.relative(root, file));
        }
    console.log('tokens: done');
}
