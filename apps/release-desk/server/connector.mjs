import { randomBytes } from 'node:crypto';
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { z } from 'zod';
import { DeskError, ensure, safeError } from './errors.mjs';

// What the connector may touch. Everything else (workflows, the app, build
// tooling, package files) is out of reach, so a request can never change how
// changes are tested or released.
const THEME_DIRS = /^(assets|blocks|config|layout|locales|sections|snippets|templates|src)\//;
const SAFE_PATH = /^[A-Za-z0-9_@-][A-Za-z0-9_.@-]*(?:\/[A-Za-z0-9_@-][A-Za-z0-9_.@-]*)*$/;
const GENERATED = new Set(['assets/index.css', 'assets/main.js', 'assets/global.js']);
const STORE_OWNED = new Set(['config/settings_data.json', 'config/markets.json']);
const READ_ONLY_ROOT = new Set(['README.md', 'CLAUDE.md', 'design-tokens.json', 'tailwind.config.js', 'vite.config.ts', 'package.json']);
const TEXT = /\.(liquid|json|js|mjs|ts|css|scss|svg|md|txt)$/i;
const MAX_FILE_BYTES = 256 * 1024, MAX_FILES_PER_SAVE = 20;

export function readablePath(path) {
  return typeof path === 'string' && path.length < 240 && SAFE_PATH.test(path) && !path.split('/').some(part => part === '..') && (THEME_DIRS.test(path) || READ_ONLY_ROOT.has(path));
}
export function editablePath(path) {
  return readablePath(path) && THEME_DIRS.test(path) && !GENERATED.has(path) && !STORE_OWNED.has(path) && !/\.gitkeep$/.test(path);
}
export function editRefusal(path) {
  if (!readablePath(path)) return `${path} is outside the theme. Only assets, blocks, config, layout, locales, sections, snippets, templates and src can be changed.`;
  if (GENERATED.has(path)) return `${path} is generated by the build from src/. Change the source in src/ instead; the build workflow recompiles it on the pull request.`;
  if (STORE_OWNED.has(path)) return `${path} holds the store's own settings, edited in the theme editor. It cannot be changed through Claude.`;
  if (!THEME_DIRS.test(path)) return `${path} is read-only.`;
  return null;
}
export function changeId(title) {
  const slug = String(title).toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'change';
  return `${slug}-${randomBytes(3).toString('hex')}`;
}

const text = value => ({ content: [{ type: 'text', text: typeof value === 'string' ? value : JSON.stringify(value, null, 2) }] });
const failure = error => ({ isError: true, content: [{ type: 'text', text: error instanceof DeskError ? error.message : safeError(error) }] });

export function guide(config, identity) {
  return `You are editing the Shopify theme of ${config.shop} on behalf of ${identity.name}, through Strix Release Desk.

How it works
1. Read the theme first: list_files and read_file show the current staging version.
2. start_change with a short title and the request in the person's own words. You get a change_id.
3. save_files with the complete new content of every file you change (one commit per save, recorded under ${identity.name}).
4. submit_change when it is ready. That opens a pull request into ${config.stagingBranch}.
5. Nothing goes live from here. ${identity.name} (or a colleague) opens Release Desk in the Shopify admin, tests the change, checks the preview and the staging theme, and releases it to ${config.liveBranch}.

Rules
- Only theme folders can change: assets, blocks, config, layout, locales, sections, snippets, templates, src.
- assets/index.css, assets/main.js and assets/global.js are built from src/ by the build workflow. Edit src/ (Tailwind classes, custom elements), never the built files.
- config/settings_data.json and config/markets.json belong to the store's theme editor and cannot be changed here.
- Text a customer sees belongs in locales/*.json, not hard-coded in Liquid. A new translation key must be added to every storefront locale file (locales/*.json, not *.schema.json), in that language, or the theme check fails. Keep the comment header at the top of locale files. New section settings need a default and must not rename or remove existing setting ids, because live pages use them.
- Keep changes small and focused: one request, one change. Say exactly what you changed and why when you submit.`;
}

// One MCP server per request, bound to the person behind the connection token.
export function createConnectorServer({ config, github, connectorStore, store, identity }) {
  const server = new McpServer({ name: 'strix-release-desk', version: '1.0.0' }, { instructions: guide(config, identity) });
  const limit = write => ensure(connectorStore.allow(identity.connectionId, write), 'RATE_LIMIT', write ? 'The hourly limit for saving changes has been reached.' : 'The hourly limit for reading the theme has been reached.', 429);
  const own = id => {
    const change = typeof id === 'string' ? connectorStore.change(id) : null;
    ensure(change && change.userId === identity.userId, 'CHANGE_NOT_FOUND', 'No change with that id belongs to you. Use list_changes or start_change.', 404);
    return change;
  };
  const tool = (name, meta, handler, { write = false } = {}) => server.registerTool(name, meta, async args => {
    try { limit(write); return await handler(args || {}); }
    catch (error) { store.audit(identity.userId, 'connector.rejected', { tool: name, code: error.code || 'ERROR' }); return failure(error); }
  });

  tool('get_started', { title: 'How to change this theme', description: 'Explains the rules and the release flow, and lists your open changes. Call this first.', inputSchema: {} }, async () =>
    text(`${guide(config, identity)}\n\nYour recent changes:\n${connectorStore.changesFor(identity.userId, 10).map(change => `- ${change.id}: ${change.title}${change.prNumber ? ` (pull request #${change.prNumber})` : ' (not submitted)'}`).join('\n') || '- none'}`));

  tool('list_files', { title: 'List theme files', description: 'Lists theme files on staging, or on one of your changes. Optionally only one folder, for example "sections".', inputSchema: { folder: z.string().max(80).optional(), change_id: z.string().max(80).optional() } }, async ({ folder, change_id }) => {
    const ref = change_id ? own(change_id).branch : config.stagingBranch;
    const files = (await github.tree(ref)).filter(file => readablePath(file.path) && (!folder || file.path.startsWith(`${folder.replace(/\/+$/, '')}/`)));
    return text(files.map(file => `${file.path} (${file.size} bytes)${editablePath(file.path) ? '' : ' [read-only]'}`).join('\n') || 'No files.');
  });

  tool('read_file', { title: 'Read a theme file', description: 'Returns the content of one file on staging, or on one of your changes.', inputSchema: { path: z.string().max(240), change_id: z.string().max(80).optional() } }, async ({ path, change_id }) => {
    ensure(readablePath(path), 'PATH_REFUSED', `${path} cannot be read through this connector.`, 403);
    const ref = change_id ? own(change_id).branch : config.stagingBranch;
    const file = await github.readFile(path, ref);
    if (!TEXT.test(path)) return text(`${path} is a binary file (${file.size} bytes); its content is not shown.`);
    return text(file.content.toString('utf8'));
  });

  tool('start_change', { title: 'Start a change', description: 'Starts a new change from the current staging theme. Give a short title and the request in the person\'s own words. Returns a change_id.', inputSchema: { title: z.string().min(3).max(100), request: z.string().min(3).max(4000) } }, async ({ title, request }) => {
    const id = changeId(title), branch = `claude/${id}`;
    await github.createBranch(branch, await github.branchSha(config.stagingBranch));
    connectorStore.addChange(identity, { branch, title, request });
    return text({ change_id: id, branch, next: 'Read the files you need, then save_files with the full new content, then submit_change.' });
  }, { write: true });

  tool('save_files', { title: 'Save files to a change', description: 'Writes the complete new content of up to 20 files (or deletes them) to one of your changes, as one commit under your name. Paths are relative to the theme root, for example "sections/hero.liquid".', inputSchema: {
    change_id: z.string().max(80), message: z.string().min(3).max(300),
    files: z.array(z.object({ path: z.string().max(240), content: z.string().optional(), delete: z.boolean().optional() })).min(1).max(MAX_FILES_PER_SAVE),
  } }, async ({ change_id, message, files }) => {
    const change = own(change_id);
    ensure(!change.prNumber || await github.getPull(change.prNumber).then(pr => pr.state === 'open'), 'CHANGE_CLOSED', 'This change was already merged or closed. Start a new change.', 409);
    const seen = new Set();
    for (const file of files) {
      const refusal = editRefusal(file.path); ensure(!refusal, 'PATH_REFUSED', refusal, 403);
      ensure(!seen.has(file.path), 'DUPLICATE_PATH', `${file.path} appears twice.`, 400); seen.add(file.path);
      ensure(file.delete === true ? file.content === undefined : typeof file.content === 'string', 'INVALID_FILE', `Give either content or delete: true for ${file.path}.`, 400);
      if (!file.delete) {
        ensure(Buffer.byteLength(file.content) <= MAX_FILE_BYTES, 'FILE_TOO_LARGE', `${file.path} is larger than 256 KB.`, 413);
        ensure(TEXT.test(file.path), 'BINARY_REFUSED', `${file.path}: only text files can be written. Upload images in Shopify Files instead.`, 403);
        if (file.path.endsWith('.json')) { try { JSON.parse(file.content.replace(/^\s*\/\*[\s\S]*?\*\//, '')); } catch { throw new DeskError('INVALID_JSON', `${file.path} is not valid JSON.`, 400); } }
      }
    }
    const sha = await github.commitFiles(change.branch, { message: `${message}\n\nRequested by ${identity.name} via Claude (change ${change.id}).`, files, author: { name: identity.name, email: identity.email } });
    connectorStore.touch(change.id);
    store.audit(identity.userId, 'change.saved', { changeId: change.id, commit: sha, files: files.map(file => file.path) });
    return text({ change_id: change.id, commit: sha, files: files.map(file => `${file.delete ? 'deleted' : 'saved'} ${file.path}`) });
  }, { write: true });

  tool('submit_change', { title: 'Submit a change for review', description: 'Opens a pull request from your change into staging, so it can be tested, previewed and released in Release Desk. Summarise what you changed.', inputSchema: { change_id: z.string().max(80), summary: z.string().min(3).max(4000) } }, async ({ change_id, summary }) => {
    const change = own(change_id);
    if (change.prNumber) { const pr = await github.getPull(change.prNumber); return text({ pull_request: pr.number, url: pr.html_url, state: pr.state, note: 'Already submitted. Further save_files calls update the same pull request.' }); }
    // Compare against the exact branch head: GitHub's branch-name comparison can lag a few seconds behind a fresh commit.
    const comparison = await github.compareBranches(config.stagingBranch, await github.branchSha(change.branch));
    ensure((comparison.ahead_by ?? 0) > 0, 'NOTHING_TO_SUBMIT', 'This change has no saved files yet. Use save_files first.', 409);
    const pr = await github.createPull({ title: change.title, head: change.branch, base: config.stagingBranch, body: `**Requested by ${identity.name} via Claude**\n\n> ${change.request.replace(/\n/g, '\n> ')}\n\n### What changed\n${summary}\n\n---\nChange \`${change.id}\` · test, preview and release in Release Desk (Shopify admin).` });
    connectorStore.setPull(change.id, pr.number);
    store.audit(identity.userId, 'change.submitted', { changeId: change.id, pr: pr.number });
    return text({ pull_request: pr.number, url: pr.html_url, next: `Open Release Desk in the Shopify admin of ${config.shop}: Test changes, Generate preview, Merge to staging, then release to live.` });
  }, { write: true });

  tool('change_status', { title: 'Status of a change', description: 'Shows whether one of your changes is submitted, tested, merged into staging or live.', inputSchema: { change_id: z.string().max(80) } }, async ({ change_id }) => {
    const change = own(change_id);
    if (!change.prNumber) return text({ change_id: change.id, status: 'not submitted', branch: change.branch });
    const pr = await github.getPull(change.prNumber);
    const run = store.listRuns(change.prNumber, 1)[0];
    return text({ change_id: change.id, pull_request: pr.number, url: pr.html_url, status: pr.merged ? `merged into ${pr.base.ref}` : pr.state, latest_test: run ? run.status : 'not tested', note: pr.merged ? `It is on ${config.stagingBranch}. It goes live when the staging release is merged into ${config.liveBranch} in Release Desk.` : 'Test and merge it in Release Desk.' });
  });

  tool('list_changes', { title: 'Your changes', description: 'Lists your recent changes and their pull requests.', inputSchema: {} }, async () =>
    text(connectorStore.changesFor(identity.userId, 20).map(change => ({ change_id: change.id, title: change.title, pull_request: change.prNumber, updated: change.updatedAt }))));

  return server;
}
